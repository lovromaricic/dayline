#!/bin/zsh
# Regenerates Sources/Domain/PublicSuffixData.swift from publicsuffix.org.
# The list is compiled in so the app never touches the network for it.
set -euo pipefail
cd "$(dirname "$0")/.."
TMP=$(mktemp -d)
curl -fsSL https://publicsuffix.org/list/public_suffix_list.dat -o "$TMP/psl.dat"
OUT=Sources/Domain/PublicSuffixData.swift
{
  echo "// Generated by scripts/update-psl.sh from https://publicsuffix.org/list/public_suffix_list.dat"
  echo "// on $(date -u +%Y-%m-%d). Mozilla Public License 2.0. Do not edit."
  echo 'let publicSuffixData = #"""'
  grep -vE '^\s*(//|$)' "$TMP/psl.dat" | sed -E 's/[[:space:]].*$//'
  echo '"""#'
} > "$OUT"
rm -rf "$TMP"
echo "wrote $OUT ($(grep -c '' "$OUT") lines)"
